-- PhoneMatch DZ — Phase 3.5
-- Run this SQL once in Supabase SQL Editor.

create table if not exists public.phone_offers (
  id bigint generated by default as identity primary key,
  phone_name text not null,
  store_name text not null,
  price_dzd integer not null check (price_dzd > 0),
  product_url text,
  wilaya text,
  stock_status text default 'unknown',
  source_type text default 'public_listing',
  confidence numeric(4,3) default 0.500,
  observed_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create index if not exists phone_offers_phone_name_idx
  on public.phone_offers(phone_name);

create index if not exists phone_offers_observed_at_idx
  on public.phone_offers(observed_at desc);

-- Keep the public website read-only.
alter table public.phone_offers enable row level security;

drop policy if exists "public can read phone offers" on public.phone_offers;
create policy "public can read phone offers"
on public.phone_offers
for select
to anon, authenticated
using (true);

-- The GitHub Actions updater uses the service-role key.
-- Service-role bypasses RLS; NEVER put that key in app.js or the website.

create or replace view public.phone_best_offers as
select distinct on (phone_name)
  phone_name,
  store_name,
  price_dzd,
  product_url,
  wilaya,
  stock_status,
  confidence,
  observed_at
from public.phone_offers
order by phone_name, price_dzd asc, observed_at desc;

grant select on public.phone_offers to anon, authenticated;
grant select on public.phone_best_offers to anon, authenticated;
